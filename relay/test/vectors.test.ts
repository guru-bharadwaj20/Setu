// Shared protocol vectors in docs/vectors/packets-v1.txt. The Kotlin
// protocol module checks the same file, so the phone and the relay cannot
// drift apart. Regenerate with SETU_WRITE_VECTORS=1 npm test, then review the diff.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { PacketType, type PacketBody, create, decode, encode, fromHex, signerFromSeed, toHex } from "../src/packet";
import { shortCodeOf } from "../src/shortcode";
import type { Bytes } from "../src/cbor";

const FILE = fileURLToPath(new URL("../../docs/vectors/packets-v1.txt", import.meta.url));
const NOW = 1_800_000_000;
const SEED = "9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60";
const SEED2 = "4ccd089b28ff96da9db6c346ec114e0f5b8a319f35aba624da8cf6ed4fb8a6fb";

interface Spec { name: string; seed: string; hops: number; body: Omit<PacketBody, "origin">; refFrom?: string }

const SPECS: Spec[] = [
  { name: "sos-basic", seed: SEED, hops: 0, body: { type: PacketType.SOS, ts: NOW - 60, latE5: 1297000, lonE5: 7759000, accuracyM: 12, headcount: 3, needs: 5, battery: 40, ttl: 172_800 } },
  { name: "sos-south-west-with-note", seed: SEED2, hops: 3, body: { type: PacketType.SOS, ts: NOW - 3600, latE5: -3375000, lonE5: -7050000, accuracyM: 250, headcount: 99, needs: 31, battery: 3, ttl: 172_800, note: "roof, 2 kids" } },
  { name: "sos-unicode-note", seed: SEED, hops: 31, body: { type: PacketType.SOS, ts: NOW, latE5: 2659000, lonE5: 9174000, accuracyM: 0, headcount: 1, needs: 1, battery: 100, ttl: 1, note: "पानी चाहिए" } },
  { name: "ack-for-sos-basic", seed: SEED2, hops: 1, refFrom: "sos-basic", body: { type: PacketType.ACK, ts: NOW + 30, latE5: 1297000, lonE5: 7759000, accuracyM: 0, headcount: 0, needs: 0, battery: 100, ttl: 259_200 } },
  { name: "safe", seed: SEED, hops: 2, body: { type: PacketType.SAFE, ts: NOW + 600, latE5: 1297000, lonE5: 7759000, accuracyM: 0, headcount: 0, needs: 0, battery: 55, ttl: 86_400 } },
];

const FIELDS = ["type", "ts", "latE5", "lonE5", "accuracyM", "headcount", "needs", "battery", "ttl", "ref", "note"] as const;

async function generate(): Promise<string> {
  const ids = new Map<string, Bytes>();
  const out = [
    "# Setu protocol v1 packet vectors. Generated by relay/test/vectors.test.ts,",
    "# checked by the Kotlin protocol tests too. Blocks are separated by blank lines.",
    `# Validate with now = ${NOW}. Hex is lowercase; the note is UTF-8 text.`,
  ];
  for (const s of SPECS) {
    const signer = await signerFromSeed(fromHex(s.seed));
    const body: PacketBody = { origin: signer.publicKey, ...s.body };
    if (s.refFrom) body.ref = ids.get(s.refFrom)!;
    const p = { ...(await create(body, signer)), hops: s.hops };
    ids.set(s.name, p.id);
    out.push("", `name: ${s.name}`, `seed: ${s.seed}`, `origin: ${toHex(signer.publicKey)}`);
    for (const f of FIELDS) {
      const v = body[f];
      if (v === undefined) continue;
      out.push(`${f}: ${v instanceof Uint8Array ? toHex(v) : String(v)}`);
    }
    out.push(`hops: ${s.hops}`, `body: ${toHex(p.bodyBytes)}`, `wire: ${toHex(encode(p))}`, `id: ${toHex(p.id)}`, `code: ${await shortCodeOf(signer.publicKey)}`);
  }
  return out.join("\n") + "\n";
}

describe("shared vectors", () => {
  it("match docs/vectors/packets-v1.txt", async () => {
    const text = await generate();
    if (process.env.SETU_WRITE_VECTORS) writeFileSync(FILE, text);
    expect(readFileSync(FILE, "utf8").replace(/\r\n/g, "\n")).toBe(text);
  });

  it("decode back to the same fields", async () => {
    const blocks = readFileSync(FILE, "utf8").replace(/\r\n/g, "\n").split("\n\n").slice(1);
    expect(blocks).toHaveLength(SPECS.length);
    for (const b of blocks) {
      const kv = Object.fromEntries(b.trim().split("\n").map((l: string) => [l.slice(0, l.indexOf(":")), l.slice(l.indexOf(":") + 2)]));
      const p = await decode(fromHex(kv.wire!), NOW);
      expect(toHex(p.id)).toBe(kv.id);
      expect(p.hops).toBe(Number(kv.hops));
      expect(p.body.note ?? undefined).toBe(kv.note);
    }
  });
});
